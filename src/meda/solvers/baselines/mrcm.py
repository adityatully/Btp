"""MRCM: multiple-reactant cost minimisation on MEDA (Liang et al., ASP-DAC 2019; SPEC 10.4).

Top down from the target droplet (composition c, volume v): a mix of T units (v <= T <= M; the
paper's mixer is 8 units, here the chip's M) blends pure reactants and intermediate droplets in
a mixing model S; for each model the children are the ones with the smallest total
concentration-vector sum (the paper's ILP), and an intermediate child is grown the same way until
every leaf is a pure reactant. Of all trees, MRCM keeps the cheapest in reactant cost sum W_i R_i,
then the fewest mixes, then the least waste. Fig. 3(a): <25, 31, 44> at 4X with R1 dearest is
3 mixes, reactants 1 / 2 / 6, waste 5; the ILP gives <0,3,22>, <1,0,0>, <0,1,0> for S = <2,1,1>
and <1,3,0>, <1,0,0>, <0,0,1>, <0,4,1> for S = <1,1,2,1>.

Our reading of what the paper leaves open (`notes/lit_bench/selection.md`):
- A mixing model is written as the units drawn from each pure reactant plus at most two
  intermediate children (the paper's examples have one or two); the children of a model are the
  ones with the smallest sum of reduced denominators (its "sum of the concentration vector").
- An intermediate child has a smaller denominator than its parent and no prime factor above M
  ("can be generated by original reactants"); this also makes the search finite.
- The trees do not share droplets, so the cheapest tree is found by memoised recursion over
  (composition, volume) instead of listing every tree; the result is the same.
- The target is built exactly; a target whose denominator has a prime factor above M is not
  applicable (the paper rounds to a precision P it does not choose per problem).
- The search counts children it tries; above `SEARCH_BUDGET` the problem is not applicable.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass
from math import gcd

from meda.core.composition import Composition, Rational
from meda.core.costs import CostWeights
from meda.core.problem import Instance
from meda.solvers.baselines.paper_graph import In, NotApplicable, PaperGraph, single_target

SEARCH_BUDGET = 2_000_000


@dataclass(frozen=True, slots=True)
class _Tree:
    key: tuple[Rational, int, int]  # (reactant cost, mixes, waste)
    pure: tuple[int, ...]  # units of each reactant drawn at this node
    children: tuple[tuple[int, _Tree], ...]  # (units taken, subtree)
    volume: int


def smooth(n: int, m: int) -> bool:
    for p in range(2, m + 1):
        while n % p == 0:
            n //= p
    return n == 1


def mrcm(instance: Instance, weights: CostWeights) -> PaperGraph:
    single_target(instance)
    target, chip = instance.targets[0], instance.chip
    m = chip.max_mix_volume
    if not smooth(target.composition.den, m):
        raise NotApplicable(
            f"{target.composition}: denominator has a prime factor above M = {m} (MRCM builds "
            f"the target exactly)"
        )
    w = tuple(weights.fluid_weight(f.kind) for f in instance.fluids)
    search = _Search(w, max(chip.min_mix_volume, 2), m)
    tree = search.best(target.composition, target.droplet_volume)
    if tree is None:
        raise NotApplicable(f"MRCM finds no tree for {target.composition} at M = {m}")
    nodes: list[tuple[In, ...]] = []
    _emit(tree, nodes)
    return PaperGraph(instance.num_fluids, tuple(nodes))


def _emit(tree: _Tree, nodes: list[tuple[In, ...]]) -> int:
    ins = [In(u, fluid=f) for f, u in enumerate(tree.pure) if u]
    for units, child in tree.children:
        ins.append(In(units, node=_emit(child, nodes)))
    nodes.append(tuple(ins))
    return len(nodes) - 1


class _Search:
    def __init__(self, w: tuple[Rational, ...], lo: int, m: int) -> None:
        self.w, self.lo, self.m = w, lo, m
        self.memo: dict[tuple[Composition, int], _Tree | None] = {}
        self.budget = SEARCH_BUDGET

    def tick(self, n: int = 1) -> None:
        self.budget -= n
        if self.budget < 0:
            raise NotApplicable(f"MRCM's search exceeded {SEARCH_BUDGET} candidate children")

    def best(self, c: Composition, v: int) -> _Tree | None:
        if (c, v) in self.memo:
            return self.memo[(c, v)]
        self.memo[(c, v)] = None  # guards against a cycle while this node is open
        found: _Tree | None = None
        for model in self.models(c, v):
            tree = self.grow(model, v)
            if tree is not None and (found is None or tree.key < found.key):
                found = tree
        self.memo[(c, v)] = found
        return found

    def models(self, c: Composition, v: int):
        """One model per mixing ratio S of T units (v <= T <= M, at least two parts): the
        children with the least total concentration-vector sum (the paper's ILP), as
        (T, pure units per reactant, intermediate children)."""
        for t in range(max(v, self.lo), self.m + 1):
            caps = [t * n // c.den for n in c.num]
            for parts in _partitions(t, t):
                if len(parts) < 2:
                    continue
                choice = self.ilp(c, t, parts, caps)
                if choice is not None:
                    yield t, choice[2], choice[3]

    def ilp(self, c: Composition, t: int, parts: tuple[int, ...], caps: list[int]):
        """(sum, pure cost, pure units, children) with the least sum for the model `parts`;
        ties go to the cheaper pure draw. At most two parts are intermediate."""
        best = None
        m = len(parts)
        for k in (0, 1, 2):
            if best is not None and best[0] <= m - k + 2 * k:
                break  # a model with k intermediates sums to at least m - k + 2k
            for inter in sorted(set(itertools.combinations(parts, k))):
                pure_parts = list(parts)
                for x in inter:
                    pure_parts.remove(x)
                for pure in _assignments(pure_parts, caps):
                    self.tick()
                    r = [t * n - p * c.den for n, p in zip(c.num, pure, strict=True)]
                    if k == 0:
                        if any(r) or sum(1 for p in pure if p) < 2:
                            continue
                        kids: tuple[tuple[int, Composition], ...] = ()
                        total = len(pure_parts)
                    elif k == 1:
                        one = self.child(r, inter[0] * c.den, c)
                        if one is None:
                            continue
                        kids, total = ((inter[0], one),), len(pure_parts) + one.den
                    else:
                        room = None if best is None else best[0] - len(pure_parts)
                        two = self.split(r, inter[0], inter[1], c.den, c, room)
                        if two is None:
                            continue
                        kids = two
                        total = len(pure_parts) + two[0][1].den + two[1][1].den
                    cost = sum((w * p for w, p in zip(self.w, pure, strict=True)), Rational.of(0))
                    if best is None or (total, cost) < best[:2]:
                        best = (total, cost, pure, kids)
        return best

    def child(self, r: list[int], scale: int, parent: Composition) -> Composition | None:
        g = gcd(*r, scale)
        if sum(1 for x in r if x) < 2:
            return None  # pure: drawn from the reservoir instead
        comp = Composition.from_ints(tuple(x // g for x in r), scale // g)
        if comp.den >= parent.den or not smooth(comp.den, self.m):
            return None
        return comp

    def split(
        self, r: list[int], sa: int, sb: int, d: int, parent: Composition, room: int | None
    ) -> tuple[tuple[int, Composition], tuple[int, Composition]] | None:
        """Two intermediate children of sa and sb units with the least total denominator,
        below `room` when given."""
        best: tuple[int, Composition, Composition] | None = None
        scale = sa * d
        for da in sorted(x for x in range(2, parent.den) if scale % x == 0):
            limit = room if best is None else best[0]
            if limit is not None and da + 2 > limit:
                break
            if not smooth(da, self.m):
                continue
            unit = scale // da  # r_a = unit * q, sum(q) = da
            caps = [x // unit for x in r]
            for q in _compositions(da, caps):
                self.tick()
                if gcd(*q, da) != 1 or sum(1 for x in q if x) < 2:
                    continue
                rb = [x - unit * y for x, y in zip(r, q, strict=True)]
                cb = self.child(rb, sb * d, parent)
                if cb is None:
                    continue
                ca = Composition.from_ints(tuple(q), da)
                if ca == cb:
                    continue
                total = da + cb.den
                if room is not None and total > room:
                    continue
                if best is None or total < best[0]:
                    best = (total, ca, cb)
        if best is None:
            return None
        return (sa, best[1]), (sb, best[2])

    def grow(self, model, v: int) -> _Tree | None:
        """The tree of one mixing model; its waste counts what the parent leaves of it."""
        t, pure, inter = model
        cost = sum((w * p for w, p in zip(self.w, pure, strict=True)), Rational.of(0))
        mixes, waste = 1, t - v
        children: list[tuple[int, _Tree]] = []
        for units, comp in inter:
            sub = self.best(comp, units)
            if sub is None:
                return None
            children.append((units, sub))
            cost = cost + sub.key[0]
            mixes += sub.key[1]
            waste += sub.key[2]
        return _Tree((cost, mixes, waste), tuple(pure), tuple(children), t)


def _partitions(total: int, top: int):
    """Partitions of `total` into parts of at most `top`, in non-increasing order."""
    if total == 0:
        yield ()
        return
    for first in range(min(total, top), 0, -1):
        for rest in _partitions(total - first, first):
            yield (first, *rest)


def _assignments(parts: list[int], caps: list[int]) -> set[tuple[int, ...]]:
    """Units drawn per reactant when each pure part goes to one reactant within `caps`."""
    out: set[tuple[int, ...]] = set()

    def walk(i: int, acc: list[int], low: int) -> None:
        if i == len(parts):
            out.add(tuple(acc))
            return
        start = low if i and parts[i] == parts[i - 1] else 0
        for f in range(start, len(caps)):
            if acc[f] + parts[i] <= caps[f]:
                acc[f] += parts[i]
                walk(i + 1, acc, f)
                acc[f] -= parts[i]

    walk(0, [0] * len(caps), 0)
    return out


def _compositions(total: int, caps: list[int]):
    """Integer vectors q with sum `total` and q_i <= caps_i."""
    if len(caps) == 1:
        if total <= caps[0]:
            yield (total,)
        return
    for x in range(min(total, caps[0]), -1, -1):
        if total - x <= sum(caps[1:]):
            for rest in _compositions(total - x, caps[1:]):
                yield (x, *rest)
